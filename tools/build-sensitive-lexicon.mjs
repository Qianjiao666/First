import fs from "node:fs/promises";

const sourceUrl = new URL("../assets/data/sensitive-lexicon-source/words.txt", import.meta.url);
const browserUrl = new URL("../assets/js/security/sensitive-lexicon.js", import.meta.url);
const backendUrl = new URL("../supabase/functions/_shared/sensitive-lexicon.ts", import.meta.url);

const terms = (await fs.readFile(sourceUrl, "utf8"))
  .split("\n")
  .map((term) => term.trim())
  .filter(Boolean);

const serialized = JSON.stringify(terms, null, 2);
const source = `// Generated by tools/build-sensitive-lexicon.mjs. Do not edit the upstream snapshot by hand.\n`
  + `export const OPEN_SOURCE_WARN_WORDS = Object.freeze(${serialized});\n\n`
  + `export const DEFAULT_BLOCK_WORDS = Object.freeze([\n`
  + `  "受控高风险示例词",\n`
  + `]);\n\n`
  + `export const CUSTOM_WARN_WORDS = Object.freeze([]);\n`
  + `export const CUSTOM_BLOCK_WORDS = Object.freeze([]);\n`;

await fs.mkdir(new URL("../assets/js/security/", import.meta.url), { recursive: true });
await fs.writeFile(browserUrl, source, "utf8");
await fs.writeFile(backendUrl, source, "utf8");
